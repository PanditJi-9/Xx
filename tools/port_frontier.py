#!/usr/bin/env python3
"""Write the measured compilation frontier to docs/port/FRONTIER.md.

Two different questions are answered here, and they must not be mixed:

* `port_slice.py` answers "which units does the import graph allow?" — its rejected units each
  carry the import that stopped them.
* javac answers "which of those actually compile?" — the CI loop removes every file the compiler
  refuses and runs again. Its per-round logs are the evidence for this half.

The output is a report, not a promise: every number comes from a file this run produced.

Usage:
    python3 tools/port_frontier.py --app GameSpace --run 12345 \\
        --slice work/port/GameSpace/slice.json \\
        --logs '/tmp/javac-round-*.log' --removed /tmp/removed.txt \\
        --out docs/port/FRONTIER.md
    python3 tools/port_frontier.py --self-test
"""
from __future__ import annotations

import argparse
import glob
import json
import re
import sys
from collections import Counter
from pathlib import Path

FILE_ERROR = re.compile(r"materials/sources/(.+?\.java):\d+: error: (.*)")
ROUND_NAME = re.compile(r"javac-round-(\d+)\.log$")


def log_order(path: Path) -> tuple[int, int | str]:
    """Sort round 2 before round 10, not after it.

    `sorted()` on the file names is lexicographic: `javac-round-10.log` sorts before
    `javac-round-9.log`, so the "last" log was read from the wrong round. Run 44874120151
    was clean after round 15 while this tool reported BUILD FAILED from round 9.
    """
    found = ROUND_NAME.search(path.name)
    return (0, int(found.group(1))) if found else (1, path.name)


def parse_log(path: Path) -> tuple[dict[str, str], int]:
    """First error per unit and total error lines, from one javac round."""
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    errors: dict[str, str] = {}
    total = 0
    for index, line in enumerate(lines):
        found = FILE_ERROR.search(line)
        if not found:
            continue
        total += 1
        unit, message = found.group(1).strip(), found.group(2).strip()
        if unit in errors:
            continue
        detail = ""
        if "cannot find symbol" in message:
            for follow in lines[index + 1 : index + 8]:
                if FILE_ERROR.search(follow) or "error:" in follow:
                    break
                if "symbol:" in follow:
                    detail = follow.split("symbol:", 1)[1].strip().removeprefix("class ")
                    break
        errors[unit] = message + (f" [{detail}]" if detail else "")
    return errors, total


def group_gap(reason: str, available: list[str]) -> str:
    """The dependency a rejection asks for, at the coarsest measured prefix."""
    imported = reason.split(": ", 1)[1]
    for prefix in sorted(available, key=len, reverse=True):
        if imported.startswith(prefix):
            return prefix
    # Two segments is the group a Maven coordinate is named after (`androidx.media3`,
    # `com.google.gson`); the trailing dot keeps it in the same notation as a declared prefix.
    return ".".join(imported.split(".")[:2]) + "."


def render(app: str, run: str, slice_data: dict, logs: list[Path], removed: list[str]) -> str:
    logs = sorted(logs, key=log_order)
    total = slice_data.get("total", 0)
    selected = slice_data.get("selected", [])
    rejected = slice_data.get("rejected", {})
    buckets = slice_data.get("buckets", {})
    available = slice_data.get("available", [])

    rows = [
        f"# {app} — compilation frontier",
        "",
        "Generated by `tools/port_frontier.py`"
        + (f" from run `{run}`" if run else "")
        + ". Every number below was read from this run's slice or javac logs; nothing is estimated.",
        "",
        "## 1. Import fixpoint (`port_slice.py`)",
        "",
        "| corpus | selected | rejected | declared dependency prefixes |",
        "| ---: | ---: | ---: | ---: |",
        f"| {total} | {len(selected)} | {len(rejected)} | {len(available)} |",
        "",
        "Rejection buckets:",
        "",
        "| bucket | units |",
        "| --- | ---: |",
    ]
    for key, value in buckets.items():
        rows.append(f"| `{key}` | {value} |")

    gaps = Counter(
        group_gap(reason, available)
        for reason in rejected.values()
        if reason.startswith("library not linked: ")
        and not any(reason.split(": ", 1)[1].startswith(prefix) for prefix in available)
    )
    if gaps:
        rows += ["", "### Remaining `library not linked` gaps (top 15)", "", "| import root | units |", "| --- | ---: |"]
        for key, value in gaps.most_common(15):
            rows.append(f"| `{key}` | {value} |")
    elif rejected:
        rows += ["", "No unit is rejected for a library import in this slice."]

    if available:
        rows += ["", "### Declared dependencies", ""]
        rows += [f"- `{prefix}`" for prefix in available]

    rows += [
        "",
        "## 2. javac frontier",
        "",
    ]
    if not logs:
        rows.append("No per-round javac log was available in this run.")
    else:
        all_errors: dict[str, str] = {}
        rows += ["| round | units with errors | error lines |", "| ---: | ---: | ---: |"]
        for position, log in enumerate(logs, 1):
            errors, count = parse_log(log)
            for unit, message in errors.items():
                all_errors.setdefault(unit, message)
            label = ROUND_NAME.search(log.name)
            rows.append(f"| {label.group(1) if label else position} | {len(errors)} | {count} |")
        rows += [
            "",
            f"The compiler removed {len(removed)} unit(s) across these rounds"
            if removed
            else "The compiler removed no unit in the rounds it ran.",
            "",
        ]
        last_text = logs[-1].read_text(encoding="utf-8", errors="replace")
        if "BUILD SUCCESSFUL" in last_text:
            rows += [
                "Final javac state: **clean** (`BUILD SUCCESSFUL`). The surviving units were accepted,"
                " and only they may be sealed.",
                "",
            ]
        else:
            rows += [
                "Final javac state: **not clean** (`BUILD FAILED`). Nothing from this run may be sealed;",
                " the remaining errors are in the table below.",
                "",
            ]
        if all_errors:
            rows += ["Units the compiler refused (first error seen in any round):", "", "| unit | first error |", "| --- | --- |"]
            for unit in sorted(all_errors):
                message = all_errors[unit].replace("|", "\\|")
                rows.append(f"| `{unit}` | `{message}` |")
        elif removed:
            rows += ["The removed list is below; its round log did not keep a parseable error."]
        if removed:
            rows += ["", "### Units removed", ""]
            rows += [f"- `{unit}`" for unit in removed]

    rows += [
        "",
        "## 3. What this run proves",
        "",
        "- A unit in the fixpoint had every import answered by the platform, the app, or a declared",
        "  dependency; javac then accepted it or named the exact line that still fails.",
        "- `compileOnly` dependencies buy compilation only. Their classes are not in the APK yet;",
        "  runtime availability is a separate measurement and is not claimed here.",
        "",
    ]
    return "\n".join(rows)


def read_slice(path: Path) -> dict:
    if not path.is_file():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except ValueError:
        return {}


def read_removed(path: Path) -> list[str]:
    if not path.is_file():
        return []
    return sorted({line.strip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()})


def self_test() -> int:
    import tempfile

    checks: list[tuple[str, bool]] = []
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        slice_path = root / "slice.json"
        slice_path.write_text(
            json.dumps(
                {
                    "total": 10,
                    "selected": ["cn/nubia/a.java", "cn/nubia/b.java"],
                    "available": ["androidx.core.", "com.google.gson."],
                    "rejected": {
                        "cn/nubia/c.java": "library not linked: androidx.media3.common.MediaItem",
                        "cn/nubia/d.java": "library not linked: androidx.media3.ui.PlayerView",
                        "cn/nubia/e.java": "library not linked: com.google.gson.Gson",
                        "cn/nubia/f.java": "vendor framework: cn.nubia.panel.Power",
                    },
                    "buckets": {"library not linked": 3, "vendor framework": 1},
                }
            ),
            encoding="utf-8",
        )
        log = root / "javac-round-2.log"
        log.write_text(
            "apps/gamespace/materials/sources/cn/nubia/c.java:12: error: cannot find symbol\n"
            "  symbol:   class MediaItem\n"
            "  location: class c\n"
            "apps/gamespace/materials/sources/cn/nubia/c.java:20: error: cannot find symbol\n"
            "apps/gamespace/materials/sources/cn/nubia/g.java:3: error: package does not exist\n"
            "BUILD FAILED\n",
            encoding="utf-8",
        )
        removed_path = root / "removed.txt"
        removed_path.write_text("cn/nubia/c.java\ncn/nubia/g.java\n", encoding="utf-8")

        data = read_slice(slice_path)
        errors, count = parse_log(log)
        checks.append(("error lines are counted", count == 3))
        checks.append(("one entry per unit", set(errors) == {"cn/nubia/c.java", "cn/nubia/g.java"}))
        checks.append(("the first error is kept", "MediaItem" in errors["cn/nubia/c.java"]))
        checks.append(("symbol detail is captured", errors["cn/nubia/c.java"].endswith("[MediaItem]")))
        checks.append(("the removed list is read", read_removed(removed_path) == ["cn/nubia/c.java", "cn/nubia/g.java"]))
        report = render("GameSpace", "1", data, [log], read_removed(removed_path))
        checks.append(("the slice total is reported", "| 10 | 2 | 4 | 2 |" in report))
        checks.append(("the media3 gap is grouped", "| `androidx.media3.` | 2 |" in report))
        checks.append(("a declared prefix is recognised", "`com.google.gson.`" in report))
        checks.append(("javac units are reported", "`cn/nubia/c.java` | `cannot find symbol [MediaItem]`" in report))
        checks.append(("removed units are listed", "- `cn/nubia/g.java`" in report))
        checks.append(("declared dependencies are not called runtime-ready", "not in the APK yet" in report))
        checks.append(("a failed final round forbids sealing", "Final javac state: **not clean**" in report))
        clean_log = root / "javac-round-10.log"
        clean_log.write_text("BUILD SUCCESSFUL\n", encoding="utf-8")
        ordered = render("GameSpace", "1", data, [clean_log, log], read_removed(removed_path))
        checks.append(
            (
                "round 2 is printed before round 10",
                ordered.index("\n| 2 | 2 | 3 |") < ordered.index("\n| 10 | 0 | 0 |"),
            )
        )
        checks.append(
            (
                "the final state is read from the highest round",
                "Final javac state: **clean**" in ordered,
            )
        )
        empty = render("GameSpace", "", {}, [], [])
        checks.append(("a missing slice does not invent numbers", "| 0 | 0 | 0 | 0 |" in empty))
        checks.append(("a missing log is stated", "No per-round javac log" in empty))

    failed = [name for name, ok in checks if not ok]
    for name, ok in checks:
        print(("ok   " if ok else "FAIL ") + name)
    if failed:
        return 1
    print(f"self-test OK: {len(checks)} cases")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--app", default="")
    parser.add_argument("--run", default="")
    parser.add_argument("--slice", required=False)
    parser.add_argument("--logs", default="")
    parser.add_argument("--removed", default="")
    parser.add_argument("--out", default="")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)
    if args.self_test:
        return self_test()

    data = read_slice(Path(args.slice)) if args.slice else {}
    logs = [Path(item) for item in sorted(glob.glob(args.logs))] if args.logs else []
    removed = read_removed(Path(args.removed)) if args.removed else []
    report = render(args.app or "app", args.run, data, logs, removed)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(report, encoding="utf-8")
        print(f"frontier: {out} (run {args.run or 'n/a'}, {len(logs)} javac round(s), {len(removed)} removed)")
    else:
        print(report)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
