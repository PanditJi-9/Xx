#!/usr/bin/env python3
"""Turn the measured manifest inventory into a component catalog (the feature surface).

Why this exists: the plan asks for a Feature Catalog, and the only honest seed for it
is what the apps actually declare — activities, services, receivers and providers with
their export flag and the actions they answer. Each row is a place an independent
rebuild has to reproduce behaviour, or explicitly declare unsupported.

Usage:
    python3 tools/make_component_catalog.py docs/audit/apk-inventory.json \
        docs/audit/COMPONENT_CATALOG.md
"""

from __future__ import annotations

import json
import sys

PROT = {0: "normal", 1: "dangerous", 2: "signature", 3: "signature|privileged"}


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    with open(argv[0], encoding="utf-8") as fh:
        inv = json.load(fh)
    out = [
        "# COMPONENT_CATALOG — declared surface of the 23 apps",
        "",
        "Generated by `tools/make_component_catalog.py` from `docs/audit/apk-inventory.json`.",
        "Every row exists in the APK's manifest. Existence is not behaviour: a component that",
        "is declared may still be dead on a given ROM.",
        "",
    ]
    for row in inv.get("apks", []):
        if "error" in row:
            out += [f"## {row['file']} — unreadable ({row['error']})", ""]
            continue
        out += [f"## {row['file']} — `{row['package']}` {row['versionName']} ({row['versionCode']})", ""]
        if row.get("declaredPermissions"):
            out.append("Declared permissions: " + ", ".join(
                f"`{p['name']}`({PROT.get(int(p['protectionLevel'], 0) if p['protectionLevel'].isdigit() else 0, p['protectionLevel'])})"
                for p in row["declaredPermissions"]))
            out.append("")
        for kind, label in (
            ("activities", "Activities"),
            ("services", "Services"),
            ("receivers", "Receivers"),
            ("providers", "Providers"),
        ):
            comps = row["components"].get(kind, [])
            if not comps:
                continue
            out += [f"**{label}** ({len(comps)})", "", "| component | exported | permission | actions |",
                    "| --- | --- | --- | --- |"]
            for c in comps:
                acts = "<br>".join(c.get("actions", [])) or "—"
                out.append(
                    f"| `{c.get('name','?')}` | {c.get('exported') or '—'} | `{c.get('permission') or '—'}` | {acts} |"
                )
            out.append("")
    with open(argv[1], "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {argv[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
