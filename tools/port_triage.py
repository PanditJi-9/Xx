#!/usr/bin/env python3
"""Split a decompiled RedMagic app into the three port lists.

Doctrine (docs/MASTER_PLAN.md §1): reuse the original before reimplementing anything.

  PORT_AS_IS   code or resource that compiles and runs after the package rename only
  ADAPT        needs a mechanical change: dependency, newer API, R class, file path
  REIMPLEMENT  reaches a vendor framework class that does not exist off a RedMagic ROM

The classification is textual and conservative: a file that merely *mentions* a vendor package
inside a comment is reported, not silently treated as portable — a false PORT_AS_IS is the one
error that costs a build later.

Usage:
    python3 tools/port_triage.py --sources build/port/GameSpace/sources \
        --res build/port/GameSpace/res --app cn.nubia.gamelauncher \
        --out docs/port/GameSpace_TRIAGE.md --json docs/port/gamespace.json
    python3 tools/port_triage.py --self-test
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

VENDOR_ROOTS = ("cn.nubia.", "com.zte.")
PRIVILEGED = ("android.system.", "android.app.usage.", "android.permission.")

PORT, ADAPT, REIMPL = "PORT_AS_IS", "ADAPT", "REIMPLEMENT"


def classify_source(text: str, own_package: str) -> tuple[str, str]:
    """Returns (verdict, reason). Reason is short and literal — it goes in the ledger."""
    imports = re.findall(r"^\s*import\s+([A-Za-z0-9_.]+)", text, re.M)
    vendor = [i for i in imports if i.startswith(VENDOR_ROOTS) and not i.startswith(own_package + ".")]
    if vendor:
        return REIMPL, "needs vendor framework: " + vendor[0]
    privileged = [i for i in imports if i.startswith(PRIVILEGED)]
    if privileged:
        return ADAPT, "privileged platform API: " + privileged[0]
    if own_package + ".R" in imports:
        return ADAPT, "references generated R"
    if any(i.startswith("kotlinx.") for i in imports):
        return ADAPT, "adds a kotlinx dependency"
    if re.search(r"\bR\.[a-z]+\.[A-Za-z0-9_]+", text):
        return ADAPT, "references generated R"
    if re.search(r"^\s*import\s+nd\.max\.", text, re.M):
        return REIMPL, "imports MaxManager-only package"
    return PORT, "package rename only"


def walk_sources(root: Path, own_package: str) -> list[dict]:
    rows = []
    for path in sorted(root.rglob("*")):
        if path.suffix not in (".java", ".kt", ".cpp", ".c", ".h", ".hpp"):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        verdict, reason = classify_source(text, own_package)
        rows.append({
            "unit": str(path.relative_to(root)),
            "kind": "source",
            "verdict": verdict,
            "reason": reason,
            "lines": text.count("\n") + 1,
        })
    return rows


def walk_resources(root: Path) -> list[dict]:
    rows = []
    if not root.exists():
        return rows
    for path in sorted(root.rglob("*")):
        if path.is_dir():
            continue
        rows.append({
            "unit": str(path.relative_to(root)),
            "kind": path.suffix.lstrip(".") or "file",
            "verdict": PORT,
            "reason": "resource copied as-is",
            "lines": 0,
        })
    return rows


def summarise(rows: list[dict]) -> dict:
    counts: dict[str, int] = {}
    lines: dict[str, int] = {}
    for row in rows:
        counts[row["verdict"]] = counts.get(row["verdict"], 0) + 1
        lines[row["verdict"]] = lines.get(row["verdict"], 0) + row["lines"]
    return {"counts": counts, "lines": lines, "total": len(rows)}


def render(app: str, rows: list[dict]) -> str:
    summary = summarise(rows)
    out = [
        f"# {app} — port triage",
        "",
        "Generated by `tools/port_triage.py`; do not edit. Every unit of the original is listed",
        "with the action it needs under the RedLab doctrine: reuse, adapt, or reimplement the part",
        "that cannot leave the ROM.",
        "",
        "| verdict | units | lines |",
        "| --- | --- | --- |",
    ]
    for verdict in (PORT, ADAPT, REIMPL):
        out.append(f"| `{verdict}` | {summary['counts'].get(verdict, 0)} | {summary['lines'].get(verdict, 0)} |")
    out.append(f"| **total** | **{summary['total']}** | |")
    out += ["", "## Units", "", "| unit | kind | verdict | why |", "| --- | --- | --- | --- |"]
    for row in rows[:5000]:
        out.append(f"| `{row['unit']}` | {row['kind']} | `{row['verdict']}` | {row['reason']} |")
    if len(rows) > 5000:
        out.append(f"| … | | | {len(rows) - 5000} more rows in the JSON |")
    return "\n".join(out) + "\n"


def self_test() -> int:
    checks = [
        ("plain logic is reusable",
         classify_source("import android.os.Bundle\nclass A {}", "cn.nubia.gamelauncher")[0] == PORT),
        ("vendor framework must be rebuilt",
         classify_source("import cn.nubia.gamepanel.PowerPanel\nclass A", "cn.nubia.gamelauncher")[0] == REIMPL),
        ("own package is not a vendor dependency",
         classify_source("import cn.nubia.gamelauncher.R\nclass A", "cn.nubia.gamelauncher")[0] == ADAPT),
        ("privileged platform API is an adaptation",
         classify_source("import android.system.Os\nclass A", "x.y")[0] == ADAPT),
        ("kotlinx is an adaptation",
         classify_source("import kotlinx.coroutines.Job\nclass A", "x.y")[0] == ADAPT),
        ("a comment alone does not demote a file",
         classify_source("// old cn.nubia.gamepanel.PowerPanel\nclass A", "x.y")[0] == PORT),
    ]
    failed = [name for name, ok in checks if not ok]
    for name, ok in checks:
        print(("ok   " if ok else "FAIL ") + name)
    if failed:
        return 1
    print(f"self-test OK: {len(checks)} cases")
    return 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sources")
    ap.add_argument("--res")
    ap.add_argument("--app", default="unknown")
    ap.add_argument("--package", default="")
    ap.add_argument("--out")
    ap.add_argument("--json")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args(argv)
    if args.self_test:
        return self_test()
    if not args.sources:
        print("--sources is required", file=sys.stderr)
        return 2

    own = args.package or args.app
    rows = walk_sources(Path(args.sources), own)
    if args.res:
        rows += walk_resources(Path(args.res))

    summary = summarise(rows)
    print(f"{args.app}: total={summary['total']} " + " ".join(
        f"{k}={summary['counts'].get(k, 0)}" for k in (PORT, ADAPT, REIMPL)))

    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(render(args.app, rows), encoding="utf-8")
    if args.json:
        Path(args.json).parent.mkdir(parents=True, exist_ok=True)
        Path(args.json).write_text(
            json.dumps({"app": args.app, "summary": summary, "units": rows}, ensure_ascii=False, indent=1),
            encoding="utf-8",
        )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
