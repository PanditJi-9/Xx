#!/usr/bin/env python3
"""Apply a small registry of exact source repairs before javac judges the staged units.

jadx 1.5.1 sometimes writes Java that cannot compile even though the bytecode is fine: a raw
`HashMap` whose keys are then consumed as `String`, a dead register name left in a call, or a
cast that javac 17 cannot infer through. The compiler is right to refuse these; guessing at the fix is not
allowed. Each repair below is one exact string, with the measured error that justified it, so a
reader can verify the change instead of trusting a generator.

A missing `find` string is an error, never a silent no-op: if jadx output changes, the run must
say so. A repair whose file is absent is reported as `absent` (the unit may already be sealed).

Usage:
    python3 tools/port_repairs.py --app GameSpace --run 12345 \\
        --sources redlab/apps/gamespace/materials/sources \\
        --registry redlab/apps/gamespace/repairs.json \\
        --report docs/port/REPAIRS.md
    python3 tools/port_repairs.py --self-test
"""
from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path

STATUSES = ("applied", "already", "absent")


class RepairError(Exception):
    """A registry entry does not match the staged source, so the run must stop."""


def load_registry(path: Path) -> list[dict[str, str]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    repairs = data.get("repairs")
    if not isinstance(repairs, list) or not repairs:
        raise RepairError(f"{path}: expected a non-empty `repairs` list")
    seen: set[str] = set()
    loaded: list[dict[str, str]] = []
    for index, item in enumerate(repairs, 1):
        if not isinstance(item, dict):
            raise RepairError(f"{path}: repair {index} is not an object")
        for key in ("id", "path", "find", "replace", "reason"):
            value = item.get(key)
            if not isinstance(value, str) or not value:
                raise RepairError(f"{path}: repair {index} is missing `{key}`")
        if item["id"] in seen:
            raise RepairError(f"{path}: duplicate repair id `{item['id']}`")
        if not item["find"]:
            raise RepairError(f"{path}: repair `{item['id']}` has an empty find string")
        if item["find"] == item["replace"]:
            raise RepairError(f"{path}: repair `{item['id']}` does not change anything")
        seen.add(item["id"])
        loaded.append({key: item[key] for key in ("id", "path", "find", "replace", "reason")})
    return loaded


def apply_repairs(sources: Path, repairs: list[dict[str, str]]) -> list[dict[str, str]]:
    if not sources.is_dir():
        raise RepairError(f"{sources}: source directory does not exist")
    results: list[dict[str, str]] = []
    for repair in repairs:
        target = sources / repair["path"]
        result = {"id": repair["id"], "path": repair["path"], "reason": repair["reason"]}
        if not target.is_file():
            results.append({**result, "status": "absent"})
            continue
        text = target.read_text(encoding="utf-8")
        found = text.count(repair["find"])
        if found == 0:
            if repair["replace"] in text:
                results.append({**result, "status": "already"})
                continue
            raise RepairError(
                f"{target}: repair `{repair['id']}` did not find its measured text; "
                "the source changed and the repair must be re-measured"
            )
        if found > 1:
            raise RepairError(
                f"{target}: repair `{repair['id']}` found {found} times; an exact repair must be unique"
            )
        target.write_text(text.replace(repair["find"], repair["replace"], 1), encoding="utf-8")
        results.append({**result, "status": "applied"})
    return results


def render(app: str, run: str, results: list[dict[str, str]]) -> str:
    counts = {status: 0 for status in STATUSES}
    for result in results:
        counts[result["status"]] += 1
    rows = [
        f"# {app} — source repairs",
        "",
        "Generated by `tools/port_repairs.py`"
        + (f" from run `{run}`" if run else "")
        + ". Each row is one exact string substitution applied to the staged sources before "
        "javac; a missing string fails the step instead of being ignored.",
        "",
        "| id | unit | status | measured reason |",
        "| --- | --- | --- | --- |",
    ]
    for result in results:
        reason = result["reason"].replace("|", "\\|")
        rows.append(f"| `{result['id']}` | `{result['path']}` | {result['status']} | {reason} |")
    rows += [
        "",
        f"Applied {counts['applied']}, already present {counts['already']}, "
        f"absent {counts['absent']} (unit already sealed or not staged).",
        "",
    ]
    return "\n".join(rows)


def self_test() -> int:
    checks = 0

    def check(condition: bool, message: str) -> None:
        nonlocal checks
        if not condition:
            raise SystemExit(f"self-test failed: {message}")
        checks += 1

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        sources = root / "sources"
        unit = sources / "pkg" / "Demo.java"
        unit.parent.mkdir(parents=True)
        unit.write_text("class Demo {\n    void f() { r4.size(); }\n}\n", encoding="utf-8")
        registry = root / "repairs.json"
        registry.write_text(
            json.dumps(
                {
                    "repairs": [
                        {
                            "id": "demo/dead-register",
                            "path": "pkg/Demo.java",
                            "find": "r4.size()",
                            "replace": "this.items.size()",
                            "reason": "measured dead register",
                        },
                        {
                            "id": "demo/sealed-unit",
                            "path": "pkg/Sealed.java",
                            "find": "x",
                            "replace": "y",
                            "reason": "already sealed",
                        },
                    ]
                }
            ),
            encoding="utf-8",
        )
        repairs = load_registry(registry)
        check(len(repairs) == 2, "loads every repair")
        results = apply_repairs(sources, repairs)
        check(results[0]["status"] == "applied", "applies an exact match")
        check("this.items.size()" in unit.read_text(encoding="utf-8"), "writes the replacement")
        check(results[1]["status"] == "absent", "reports an absent file without failing")
        results = apply_repairs(sources, repairs)
        check(results[0]["status"] == "already", "recognises its own replacement")
        check(unit.read_text(encoding="utf-8").count("this.items.size()") == 1, "is idempotent")

        unit.write_text("class Demo { void f() { other(); } }\n", encoding="utf-8")
        try:
            apply_repairs(sources, repairs)
        except RepairError as error:
            check("did not find its measured text" in str(error), "fails loudly when the text is gone")
        else:
            raise SystemExit("self-test failed: a missing find string was accepted")

        unit.write_text("r4.size(); r4.size();\n", encoding="utf-8")
        try:
            apply_repairs(sources, repairs)
        except RepairError as error:
            check("found 2 times" in str(error), "fails loudly on an ambiguous match")
        else:
            raise SystemExit("self-test failed: a duplicate find string was accepted")

        bad = root / "bad.json"
        bad.write_text(json.dumps({"repairs": [{"id": "x"}]}), encoding="utf-8")
        try:
            load_registry(bad)
        except RepairError as error:
            check("missing" in str(error), "rejects an incomplete registry")
        else:
            raise SystemExit("self-test failed: an incomplete registry was accepted")

        report = render("Demo", "123", results[:2])
        check("| `demo/dead-register` |" in report, "renders a repair row")
        check("Applied 0, already present 1, absent 1" in report, "renders measured counts")

    print(f"self-test: {checks} cases OK")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--self-test", action="store_true", help="run the built-in checks")
    parser.add_argument("--sources", type=Path, help="staged source tree (materials/sources)")
    parser.add_argument("--registry", type=Path, help="JSON repair registry")
    parser.add_argument("--report", type=Path, help="markdown report to write")
    parser.add_argument("--app", default="", help="app name for the report")
    parser.add_argument("--run", default="", help="CI run id for the report")
    args = parser.parse_args(argv)

    if args.self_test:
        return self_test()
    if not (args.sources and args.registry and args.report):
        parser.error("--sources, --registry and --report are required unless --self-test is used")
    try:
        results = apply_repairs(args.sources, load_registry(args.registry))
    except RepairError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(render(args.app, args.run, results), encoding="utf-8")
    counts: dict[str, int] = {}
    for result in results:
        counts[result["status"]] = counts.get(result["status"], 0) + 1
    print("repairs: " + ", ".join(f"{key}={counts[key]}" for key in STATUSES if key in counts))
    print(f"report: {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
