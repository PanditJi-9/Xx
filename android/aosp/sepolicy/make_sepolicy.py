#!/usr/bin/env python3
"""
make_sepolicy.py - turn SELinux denials from a phone into ready-to-use sepolicy rules.

Usage:
    python3 make_sepolicy.py LOG [LOG ...] [-d maxmanager] [-o maxmanager_generated.te]

LOG is any text file that contains `avc: denied` lines (dmesg or logcat). Only lines whose
source domain is `maxmanager` are used. Output: one `allow` rule per (source, target, class).
No dependencies - Python 3 only.
"""
import argparse
import re
import sys
from collections import defaultdict

AVC = re.compile(
    r"avc:\s+denied\s+\{([^}]*)\}.*?"
    r"scontext=u:r:([^:\s]+):[^\s]*\s+"
    r"tcontext=u:(?:object_r|r):([^:\s]+):[^\s]*\s+"
    r"tclass=(\S+)"
)


def collect(paths, domain):
    rules = defaultdict(set)
    seen = 0
    for path in paths:
        with open(path, encoding="utf-8", errors="replace") as handle:
            for line in handle:
                match = AVC.search(line)
                if not match:
                    continue
                perms, source, target, tclass = match.groups()
                if source != domain:
                    continue
                seen += 1
                rules[(source, target, tclass)].update(perms.split())
    return rules, seen


def render(rules, domain):
    out = [
        "# Generated by make_sepolicy.py from real denials - review before shipping.",
        "# If the build rejects a line with a neverallow error, delete that line.",
        "# That feature stays unavailable in this ROM; the rest still works.",
        "",
    ]
    for (source, target, tclass), perms in sorted(rules.items()):
        out.append(f"allow {source} {target}:{tclass} {{ {' '.join(sorted(perms))} }};")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("logs", nargs="+")
    parser.add_argument("-d", "--domain", default="maxmanager")
    parser.add_argument("-o", "--output", default="maxmanager_generated.te")
    args = parser.parse_args()

    rules, seen = collect(args.logs, args.domain)
    if not rules:
        print(f"No denials for domain '{args.domain}' found. Either everything is allowed already, "
              "or the daemon never ran in this domain (check that maxmanager_permissive.te was "
              "built in and the device booted with it).", file=sys.stderr)
        return 1
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write(render(rules, args.domain))
    print(f"{seen} denials -> {len(rules)} rules written to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
