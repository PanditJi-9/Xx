#!/usr/bin/env python3
"""
make_sepolicy.py - build a ready-to-use MaxManager sepolicy folder from a real phone.

Easiest way (3 steps):
  1. Flash your ROM with the `sepolicy/` folder of the developer bundle (it starts permissive:
     nothing is blocked, everything is only logged). Use the phone a few minutes, open
     MaxManager, give it root if you want, then Settings -> export logs.
  2. python3 make_sepolicy.py MaxManager_Logs_*.tar.gz        (the exported file)
        or, with the phone plugged in:  python3 make_sepolicy.py --adb
  3. Replace the bundle's `sepolicy/` folder with the new `sepolicy_out/` folder and rebuild.
     Repeat 1-3 until the tool says "no new rules" (it merges with what it found before).

No dependencies - Python 3 only. Output: sepolicy_out/ with maxmanager.te, maxmanager_app.te,
file_contexts, maxmanager_generated.te (the new rules) and INSTALL.txt.
"""
import argparse
import io
import os
import re
import shutil
import subprocess
import sys
import tarfile
from collections import defaultdict

AVC = re.compile(
    r"avc:\s+denied\s+\{([^}]*)\}.*?"
    r"scontext=u:r:([^:\s]+):[^\s]*\s+"
    r"tcontext=u:(?:object_r|r):([^:\s]+):[^\s]*\s+"
    r"tclass=(\S+)"
)
ALLOW = re.compile(r"^allow\s+(\S+)\s+(\S+):(\S+)\s+\{([^}]*)\};")
SIBLINGS = ("maxmanager.te", "maxmanager_app.te", "file_contexts")
# Permissions that only make sense to grant to a daemon after a human decision.
DANGEROUS = {"sys_module", "sys_rawio", "setenforce", "load_policy", "ptrace", "mac_admin", "mac_override"}
MAX_MEMBER_BYTES = 64 * 1024 * 1024


def texts_from_tar(path):
    with tarfile.open(path, "r:*") as archive:
        for member in archive.getmembers():
            if member.isfile() and member.size <= MAX_MEMBER_BYTES and member.name.endswith((".log", ".txt", ".old.log")):
                data = archive.extractfile(member).read()
                yield member.name, data.decode("utf-8", errors="replace")


def texts_from_path(path):
    if os.path.isdir(path):
        for root, _dirs, files in os.walk(path):
            for name in files:
                yield from texts_from_path(os.path.join(root, name))
    elif path.endswith((".tar.gz", ".tgz", ".tar")):
        yield from texts_from_tar(path)
    else:
        with open(path, encoding="utf-8", errors="replace") as handle:
            yield path, handle.read()


def texts_from_adb():
    for label, command in (("dmesg", ["adb", "shell", "su", "-c", "dmesg"]), ("logcat", ["adb", "logcat", "-d", "-b", "all"])):
        try:
            result = subprocess.run(command, capture_output=True, timeout=120)
        except FileNotFoundError:
            sys.exit("adb was not found. Install Android platform-tools, or pass the exported log file instead.")
        except subprocess.TimeoutExpired:
            continue
        yield f"adb:{label}", result.stdout.decode("utf-8", errors="replace")


def collect(sources, domain):
    rules = defaultdict(set)
    seen = 0
    enforcing = 0
    for _name, text in sources:
        for line in text.splitlines():
            match = AVC.search(line)
            if not match:
                continue
            perms, source, target, tclass = match.groups()
            if source != domain and target != domain:
                continue
            seen += 1
            enforcing += "permissive=0" in line
            rules[(source, target, tclass)].update(perms.split())
    return rules, seen, enforcing


def load_existing(path):
    rules = defaultdict(set)
    if os.path.exists(path):
        with open(path, encoding="utf-8") as handle:
            for line in handle:
                match = ALLOW.match(line.strip())
                if match:
                    source, target, tclass, perms = match.groups()
                    rules[(source, target, tclass)].update(perms.split())
    return rules


def render(rules):
    out = [
        "# Generated by make_sepolicy.py from real denials - review before shipping.",
        "# If the build rejects a line with a neverallow error, delete that line:",
        "# that feature stays unavailable in this ROM; everything else still works.",
        "",
    ]
    for (source, target, tclass), perms in sorted(rules.items()):
        flag = "  # REVIEW: dangerous permission, grant only if you understand it" if perms & DANGEROUS else ""
        out.append(f"allow {source} {target}:{tclass} {{ {' '.join(sorted(perms))} }};{flag}")
    return "\n".join(out) + "\n"


INSTALL = """MaxManager sepolicy - install
1. Put this whole folder in your ROM's sepolicy directory (replace the bundle's sepolicy/ folder).
   Do NOT keep maxmanager_permissive.te: this folder is the enforcing version.
2. Set ro.maxmanager.sepolicy=1 (PRODUCT_PROPERTY_OVERRIDES, or a line in product/etc/build.prop).
3. Rebuild, flash, use the phone, export the logs again and run make_sepolicy.py on them.
   When it says "no new rules", you are done.
If the build says "neverallow" for a line in maxmanager_generated.te, delete that line.
"""


def write_bundle(outdir, rules, script_dir):
    os.makedirs(outdir, exist_ok=True)
    for name in SIBLINGS:
        src = os.path.join(script_dir, name)
        if os.path.exists(src):
            shutil.copy(src, os.path.join(outdir, name))
    with open(os.path.join(outdir, "maxmanager_generated.te"), "w", encoding="utf-8") as handle:
        handle.write(render(rules))
    with open(os.path.join(outdir, "INSTALL.txt"), "w", encoding="utf-8") as handle:
        handle.write(INSTALL)


def self_test():
    sample = (
        "avc:  denied  { read open } for scontext=u:r:maxmanager:s0 tcontext=u:object_r:sysfs_x:s0 tclass=file permissive=1\n"
        "avc:  denied  { write } for scontext=u:r:maxmanager:s0 tcontext=u:object_r:sysfs_x:s0 tclass=file permissive=0\n"
        "avc:  denied  { connectto } for scontext=u:r:priv_app:s0:c1,c2 tcontext=u:r:maxmanager:s0 tclass=unix_stream_socket permissive=0\n"
        "avc:  denied  { read } for scontext=u:r:priv_app:s0 tcontext=u:object_r:sysfs:s0 tclass=file permissive=0\n"
        "avc:  denied  { ptrace } for scontext=u:r:maxmanager:s0 tcontext=u:r:system_server:s0 tclass=process permissive=1\n"
    )
    rules, seen, enforcing = collect([("t", sample)], "maxmanager")
    assert seen == 4 and enforcing == 2, (seen, enforcing)
    assert rules[("maxmanager", "sysfs_x", "file")] == {"read", "open", "write"}
    assert ("priv_app", "sysfs", "file") not in rules
    text = render(rules)
    assert "allow priv_app maxmanager:unix_stream_socket { connectto };" in text
    assert "REVIEW" in text and "allow maxmanager system_server:process { ptrace };" in text
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
        data = sample.encode()
        info = tarfile.TarInfo("log/avc_maxmanager.txt")
        info.size = len(data)
        archive.addfile(info, io.BytesIO(data))
    tmp = "/tmp/_make_sepolicy_selftest.tar.gz"
    with open(tmp, "wb") as handle:
        handle.write(buffer.getvalue())
    again, seen2, _ = collect(texts_from_path(tmp), "maxmanager")
    assert seen2 == 4 and again == rules
    os.unlink(tmp)
    print("self-test ok")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("inputs", nargs="*", help="exported log .tar.gz, a folder, or plain log files")
    parser.add_argument("--adb", action="store_true", help="read dmesg + logcat from the connected phone")
    parser.add_argument("-d", "--domain", default="maxmanager")
    parser.add_argument("-o", "--output", default="sepolicy_out",
                        help="output folder (default sepolicy_out); a name ending in .te writes only the rules file")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()

    if args.self_test:
        self_test()
        return 0
    if not args.inputs and not args.adb:
        parser.error("give the exported log file, or use --adb")

    def sources():
        for path in args.inputs:
            yield from texts_from_path(path)
        if args.adb:
            yield from texts_from_adb()

    new_rules, seen, enforcing = collect(sources(), args.domain)
    single_file = args.output.endswith(".te")
    generated = args.output if single_file else os.path.join(args.output, "maxmanager_generated.te")
    merged = load_existing(generated)
    before = {key: set(value) for key, value in merged.items()}
    for key, perms in new_rules.items():
        merged[key].update(perms)

    if not new_rules and not merged:
        print(f"No denials for domain '{args.domain}' found.\n"
              "Either the daemon never ran in that domain (is ro.maxmanager.sepolicy=1 set and the "
              "permissive file built in?), or nothing was denied.", file=sys.stderr)
        return 1

    added = sum(1 for key, perms in merged.items() if perms - before.get(key, set()))
    if single_file:
        with open(args.output, "w", encoding="utf-8") as handle:
            handle.write(render(merged))
    else:
        write_bundle(args.output, merged, os.path.dirname(os.path.abspath(__file__)))

    print(f"{seen} denials read -> {len(merged)} rules total, {added} new or extended -> {args.output}")
    if enforcing:
        print(f"Note: {enforcing} denials were logged while enforcing (permissive=0), so the daemon was "
              "blocked part-way. Add these rules, rebuild and repeat: later steps only show up after.")
    if added == 0:
        print("No new rules - you are done." if new_rules else "Nothing new in these logs.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
