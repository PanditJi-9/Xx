package nd.max.core.daemon

/**
 * إيقاع دورة رفيق الجذر (`nd.max.AppMonitor`) — **القرار نقيّ هنا، والقراءة من العتاد هناك**.
 *
 * ### العطب المقيس الذي وُلد منه هذا الملف (جولة الحرارة واللاغ)
 *
 * كانت الحلقة تدور كل **٥٠٠ م.ث دائمًا**: والشاشة مطفأة، وبلا تطبيق مُدار في المقدّمة، وفي جيب
 * المستخدم. أي **١٧٢٨٠٠ دورة في اليوم**، وفي كل دورة: نداءات Binder (قائمة العمليات · `getRecentTasks`
 * · اسم الحزمة · حِمل الشاشة · البطارية · حدا الصمت)، وكتابة ملف حالة بـ`fsync` عند كل تغيّر،
 * و`stat` كل ١٢٠ م.ث على خيط المراقبة. وهذا — لا قرار Max AI — هو ما يُقاس على الجهاز حرارةً
 * واستهلاكًا وسحبًا للبطارية في الساعات التي لا يلعب فيها أحد.
 *
 * ### والقاعدة (ثلاث حالات، وكل واحدة مُعلَّلة بما تفقده)
 *
 * | الحالة | الإيقاع | ما تفقده مقابل الكلفة |
 * | --- | --- | --- |
 * | تطبيق مُدار (مُدرج في قائمة اللعب) في المقدّمة **والشاشة مضاءة** | ٥٠٠ م.ث (**كما كان**) | لا شيء: لحظة اللعب تُبقى بلا تأخير |
 * | الشاشة مضاءة بلا تطبيق مُدار | ١٠٠٠ م.ث | ثانية واحدة في التقاط تبديل تطبيق لا يُطبَّق عليه شيء فورًا |
 * | الشاشة مطفأة | ٥٠٠٠ م.ث | تبقى حالة الشحن/جلسة العتاد على هذا الإيقاع؛ الخمول غير الموصول بالشاحن له مهلة حالة منفصلة |
 *
 * **والفرق الذي لا يُقرأ في تعليق:** الحالة الثانية كانت **لا تقع أبدًا** لأن المنادي كان يمرّر
 * «هل آخر حزمة غير فارغة؟» بدل «هل التطبيق المُدار هو الذي في المقدّمة؟» — والحزمة غير الفارغة
 * تكون المشغّل أو أي تطبيق عاديّ. فطُول اليوم كان ٥٠٠ م.ث، وكانت الحالات الثلاث على الورق فقط.
 * فصارت الحالة تُحسب من **وجود التطبيق في قائمة اللعب** (أو تعديلات حيّة على العتاد)،
 * لا من «أي اسم حزمة غير فارغة». وهذا **ليس** شرط جلسة العتاد: الجلسة وحدها تشترط
 * حقلًا صريحًا واحدًا على الأقل ([nd.max.core.gamespace.PerAppSessionRules]).
 *
 * ### ولماذا Battery Saver هنا لا في الشاشة
 *
 * «توفير البطارية» كان مفتاحًا يُكتب ويُقرأ ولا يغيّر إيقاعًا واحدًا (قِيس بالبحث: لا مستهلك
 * لـ`isPowerSaveMode` في مسار المراقبة). وربطُه بالإيقاع في **هذا الملف** يجعله قرارًا واحدًا
 * قابلًا للقياس بدل شرطٍ يُنسى في دورة. ولا يُبطَّأ **أمان**: مسار الحارس الحراري ما زال عشر
 * ثوانٍ ويعمل ما دام تطبيق مُدار في المقدّمة، وقراءة حالة الشاشة لا تُبطَّأ.
 */
object CompanionPollPolicy {

    /** الإيقاع الكامل: تطبيق مُدار في المقدّمة والشاشة مضاءة — لحظة اللعب. */
    const val ACTIVE_MS = 500L

    /** الشاشة مضاءة ولا تطبيق مُدار: تبديل التطبيق يُلتقط في ثانية. */
    const val IDLE_MS = 1_000L

    /**
     * الإيقاع الخامل **وتوفير البطارية مُفعَّل من النظام**: ثانيتان.
     *
     * **ولماذا لا ٥٠٠ كما كان:** لا شيء في هذه الحالة يُطبَّق على العتاد؛ العمل الوحيد هو معرفة
     * متى يفتح المستخدم تطبيقًا مُدارًا. وثانيتان أسوأ ما في الأمر: تأخير ثانية واحدة في تطبيق
     * إعدادات تطبيق. وأفضل ما فيه: نصف الدورات المجدولة؛ معاملات Binder واستيقاظات المعالج تحتاج جهازًا.
     */
    const val IDLE_POWER_SAVE_MS = 2_000L

    /** الشاشة مطفأة: ١٠٪ من عدد الدورات المجدولة سابقًا، لا قياسًا لاستيقاظات الجهاز. */
    const val SCREEN_OFF_MS = 5_000L

    /**
     * إيقاع دورة الاستطلاع.
     *
     * @param screenInteractive الشاشة مضاءة الآن (`PowerManager.isInteractive`).
     * @param managedAppOwnsForeground تطبيق **مُدرج في قائمة اللعب** هو الذي في المقدّمة
     *   (أو تعديلات عتاد حيّة)، لا مجرّد اسم حزمة.
     * @param powerSave وضع توفير البطارية في النظام (يُقرأ من مخبأ قصير، لا في كل دورة).
     */
    fun intervalMs(
        screenInteractive: Boolean,
        managedAppOwnsForeground: Boolean,
        powerSave: Boolean = false,
    ): Long = when {
        !screenInteractive -> SCREEN_OFF_MS
        managedAppOwnsForeground -> ACTIVE_MS
        powerSave -> IDLE_POWER_SAVE_MS
        else -> IDLE_MS
    }

    /**
     * هل التطبيق الذي في المقدّمة **مُدار** — أي مُدرج في قائمة اللعب؟
     *
     * **والمعنى الدقيق مقصود:** «مُدار» هنا يعني وجوده في قائمة اللعب (لعبة يخدمها
     * الخادم ويقرأ PIDsها)، لا «له حقل إعداد صريح». فإدخال كل حقوله `default` يبقى
     * لعبة نشطة لإيقاع المراقبة. أما **جلسة العتاد** (التقاط خط أساس/استعادة) فتشترط
     * حقلًا صريحًا واحدًا على الأقل، وهذا قرار [nd.max.core.gamespace.PerAppSessionRules]
     * في `applyPerAppConfig` — فلا يُخلط بين السؤالين في تعليق أو تقرير أو جدول.
     *
     * والشرط الأول يُغلق الحالة قبل أي قراءة؛ والثاني يبقي الإيقاع سريعًا ما دامت
     * تعديلات حيّة على العتاد (بما فيها مهلة التراجع).
     */
    fun isManagedForeground(
        lastAppliedPkg: String,
        hardwareOverridesActive: Boolean,
        appListText: String?,
    ): Boolean {
        if (lastAppliedPkg.isBlank()) return false
        if (hardwareOverridesActive) return true
        return appListText?.contains("\"$lastAppliedPkg\":") == true
    }

    /** مراقب ملف قائمة التطبيقات: فحص metadata دوري؛ ليس كل موعد مجدول استيقاظًا فعليًّا للجهاز. */
    const val CONFIG_WATCH_ACTIVE_MS = 400L
    const val CONFIG_WATCH_IDLE_MS = 1_000L

    /**
     * إيقاع المراقب والشاشة مطفأة — ثانيتان.
     *
     * الملفّ لا يُقرأ في هذه الحالة بلا مستخدم، و`stat` واحد كل ثانيتين يكشف التعديل قبل الإضاءة
     * بهامش لا يُحسّ. وكان قبل ذلك ثانية كاملة على مدار الليل.
     */
    const val CONFIG_WATCH_SCREEN_OFF_MS = 2_000L

    /**
     * الفحص الاحتياطي لملفّ الإعدادات **حين يعمل مراقب الملفّات** — دقيقة واحدة.
     *
     * **ولماذا وُجد:** `stat` كل ٤٠٠ م.ث هو ٩٠٠٠ استيقاظ في الساعة، و`stat` كل ثانيتين ليلًا
     * ١٨٠٠ — وكلّها لسؤال واحد: «هل تغيّر ملفّ الإعداد؟». و`inotify` يجيب عن السؤال نفسه
     * **بحدث** لا باستيقاظ. فصار المراقب حدثيًّا، وبقي هذا الفحص شبكةَ أمان: لو ضاعت إشارة
     * (نظام ملفّات لا يدعم `inotify`، أو مجلّد أُعيد إنشاؤه) يُلتقط التغيير في دقيقة على الأكثر.
     *
     * **والحدّ مُعلن:** التغيير العادي يُلتقط فورًا بالحدث؛ وهذا الفحص لا يُضيف تأخيرًا إليه.
     */
    const val CONFIG_WATCH_FALLBACK_MS = 60_000L

    /**
     * إعادة بناء ملفّ الحالة **والشاشة مطفأة** — كلّ خمس دقائق (`0` = كل دورة، والشاشة مضاءة).
     *
     * **العطب المقيس:** الدورة كانت تبني الحالة كل ٥ ثوانٍ ليلًا — أي ٧٢٠ بناءً في الساعة،
     * وفي كلّها حلّ المقدّمة (انعكاس + Binder) وأربع قراءات Binder (الصمت · البطارية · الشحن ·
     * اسم الحزمة). في الخمول غير الموصول بالشاحن صار البناء كلّ خمس دقائق (١٢ في الساعة،
     * **جزء من ستّين**). أمّا الشحن أو جلسة عتاد/مهلة تراجع قائمة فتبقى على إيقاع الدورة:
     * الخادم يستهلك battery_level/is_charging للتحكّم في bypass، فلا يؤخّر التوفير هذا المسار.
     * تبديل حالة الشاشة والشحن والتراجع يفرض التحديث في الدورة التالية أيضًا.
     */
    const val SCREEN_OFF_STATUS_MS = 300_000L

    /** إيقاع المراقب بحسب الحالة — نفس شرط الإيقاع الكامل، مع احترام إطفاء الشاشة. */
    fun configWatchMs(
        managedAppOwnsForeground: Boolean,
        screenInteractive: Boolean = true,
    ): Long = when {
        !screenInteractive -> CONFIG_WATCH_SCREEN_OFF_MS
        managedAppOwnsForeground -> CONFIG_WATCH_ACTIVE_MS
        else -> CONFIG_WATCH_IDLE_MS
    }

    /**
     * عدد الدورات المجدولة في الساعة عند ثبات الإيقاع، لا الاستيقاظات الفعلية للمعالج.
     *
     * **ولماذا دالّة لا تعليق:** الفرق بين ٥٠٠ و٥٠٠٠ م.ث يُقرأ في تعليق كأنه «أبطأ قليلًا»،
     * بينما هو **٧٢٠٠ ⇒ ٧٢٠ دورةً في الساعة**. الأحداث والعمل نفسه والنوم العميق تغيّر العدد
     * الفعليّ؛ هذا الحساب يثبت السياسة فقط، ولا يثبت طاقةً أو حرارةً على الجهاز.
     */
    fun wakeupsPerHour(intervalMs: Long): Long =
        if (intervalMs <= 0L) 0L else 3_600_000L / intervalMs

    /**
     * كم يمرّ بين بناءَي ملفّ الحالة: `0` = كلّ دورة (الشاشة مضاءة، فالمقدّمة تتغيّر).
     *
     * أثناء الشحن أو وجود جلسة عتاد لا يُؤجَّل التحديث ولو كانت الشاشة مطفأة.
     */
    fun statusRefreshMs(screenInteractive: Boolean, requiresLiveStatus: Boolean = false): Long =
        if (screenInteractive || requiresLiveStatus) 0L else SCREEN_OFF_STATUS_MS

    /** A failed write never advances lastRefreshAtMs; dirty changes bypass the idle throttle. */
    fun statusRefreshDue(
        nowMs: Long,
        lastRefreshAtMs: Long,
        dirty: Boolean,
        screenInteractive: Boolean,
        requiresLiveStatus: Boolean,
    ): Boolean {
        val interval = statusRefreshMs(screenInteractive, requiresLiveStatus)
        return dirty || interval == 0L || nowMs - lastRefreshAtMs >= interval
    }
}
