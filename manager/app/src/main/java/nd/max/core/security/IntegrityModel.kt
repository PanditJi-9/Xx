package nd.max.core.security

/**
 * نموذج أدلّة التلاعب — **منطق خالص بلا Android**، فيُقاس في JVM عادية.
 *
 * القاعدة التي بُني عليها هذا الملف كلّه: **التلاعب حكمٌ لا إشارة واحدة**.
 * فحصٌ واحد يحكم بـ«التطبيق معدَّل» يُنتج صنفين من العطب في وقت واحد: إمّا أن يكون
 * قابلًا للحذف بسطر واحد (فلا يحمي شيئًا)، وإمّا أن يرفض نسخة رسميّة سليمة على جهاز
 * شاذّ (فيعطّل المستخدم بلا سبب). ولذلك تُجمع الأدلّة هنا في **سجلّ ثابت** لا يُمحى،
 * ويُحكم عليه بقاعدتين معلنتين:
 *
 * 1. **دليل قاطع واحد يكفي** — وهو ما يستحيل أن يقع في تشغيل سليم: اختلاف موقّع
 *    الحزمة، أو اختلاف محتوى أصل مختوم، أو رفض المرساة الأصلية.
 * 2. **والدليل غير القاطع يحتاج تصديقًا** — مصائد التنقيح والهوك موجودة على أجهزة
 *    حقيقية بلا أي تعديل من صاحبها (مستخدم بجذور يثبّت LSPosed لتطبيق آخر، أو مطوّر
 *    وصّل مصحّحًا). فلا يُرفض التطبيق لإشارة واحدة منها، بل **لإشارتين مختلفتين**.
 *
 *    **ولا تُعدّ الإشارة الواحدة عند مواضع متعدّدة إشارتين.** والتوزيع على المواضع مفيد
 *    لسبب آخر: حذف نقطة تحقّق واحدة لا يُسقط الباقي. أمّا عدّ التكرار دليلًا فيقلب
 *    الميزة عطبًا: مستخدمٌ سطحه يحمل مكتبة هوك لتطبيق آخر يُرى في أربعة مواضع فيصير
 *    «مخترقًا» بلا ذنب. وقاعدة لا تفرّق بين الاثنين أسوأ من غيابها.
 *
 * **وما لا يُحتسب دليلًا إطلاقًا — وهذا جزء من العقد لا استثناء فيه:** وجود الجذور،
 * أو KernelSU/Magisk، أو روم مخصّص، أو SELinux في حالة `Permissive`، أو تفعيل خيارات
 * المطوّر، أو تغيير المستخدم لبياناته وإعداداته. كلّها حالات مشروعة يطلب المالك صراحةً
 * ألّا تمنع التشغيل، وهي مُثبَّتة في [IntegrityLedger.NEVER_EVIDENCE] لتُقاس لا لتُوصف.
 */

/** موضع التحقّق في دورة حياة التطبيق — التوزيع مقصود، لا فحص واحد قابل للحذف. */
enum class IntegrityCheckpoint {
    /** إقلاع العملية (`Application.onCreate`) — أول موضع، وكل موضع بعده يرث حكمه. */
    PROCESS,

    /** ظهور نشاط (`MainActivity.onCreate`/`onStart`). */
    ACTIVITY,

    /** إقلاع خدمة (`Service.onCreate`) — ومنها خدمة لوحة الألعاب. */
    SERVICE,

    /** استقبال بثّ (`BroadcastReceiver.onReceive`) — يُساء استخدامه لتشغيل غير مصرّح. */
    RECEIVER,
}

/**
 * ما يرصده المسبار.
 *
 * و`hard` ليس شدّةً في الخطورة بل **وصفًا لاحتمال الخطأ**: الإشارة القاطعة لا تتحقّق في
 * تشغيل سليم أصلًا (فلا حاجة إلى تصديق)، وغير القاطعة تتحقّق كثيرًا بلا تعديل (فتحتاج تصديقًا).
 */
enum class IntegritySignal(val hard: Boolean) {
    /** بصمة موقّع الحزمة المُثبَّتة تخالف المثبَّتة زمن البناء. إعادة تغليف ⇒ اختلاف حتميّ. */
    SIGNER_MISMATCH(true),

    /** أصل مختوم (`assets/` بامتداد `.seal`) لا يوافق بصمته المحفوظة في حزمة التطبيق. */
    SEALED_ASSET_MISMATCH(true),

    /** المرساة الأصلية عادت بحكم مستحيل (مكتبة موجودة وأجوبتها متناقضة) — لا غيابها. */
    NATIVE_ATTEST_BROKEN(true),

    /** مصحّح مرتبط بالعملية (`Debug.isDebuggerConnected`) — ونسخة release غير قابلة للتنقيح. */
    DEBUGGER_ATTACHED(false),

    /** `TracerPid` في `/proc/self/status` ليس صفرًا: أداة تتبّع تمسك العملية. */
    TRACER_ATTACHED(false),

    /** مكتبة هوك/ريث تظهر في خريطة ذاكرة العملية (`frida` · `substrate` · `xposed`). */
    HOOK_FRAMEWORK_MAPPED(false),

    /** جسر هوك على مستوى Java حاضر في مسار الأصناف (`XposedBridge` …). */
    JAVA_HOOK_BRIDGE_PRESENT(false),

    /** ملفّ المكتبة الأصلية المستخرج على القرص يخالف نسخته داخل الحزمة. */
    NATIVE_IMAGE_MISMATCH(true),

    /**
     * محتوى الحزمة لا يوافق بصماته المكتوبة في توقيعها (تحقّق توقيع كامل).
     *
     * وهي **الدليل الوحيد الذي يصمد** حين يُبطَل تحقّق النظام ويُعدَّل الـDEX مع ترك
     * بايتات التوقيع كما هي: بصمة الموقّع لم تتغيّر، والأصول قد لا تُلمَس، فيبقى هذا
     * الفحص وحده هو الذي يرى تعديل المنطق. ولا يُحتسب إلا عند **فشل صريح** في التحقّق
     * (لا عند تعذّر الفحص) — انظر [ApkContentVerification.Outcome].
     */
    APK_CONTENT_MISMATCH(true),
}

/**
 * دليل واحد: **ماذا** رُصد و**أين**. والموضع جزء من الدليل لا زينة: به تُميَّز إشارة
 * واحدة تكرّرت في موضعين (تصديق) من إشارتين مختلفتين (تصديق أيضًا) — وكلاهما يُقاس في
 * [IntegrityLedger].
 */
data class IntegrityFinding(
    val signal: IntegritySignal,
    val checkpoint: IntegrityCheckpoint,
    val detail: String = "",
) {
    /**
     * مفتاح التكرار: الإشارة في موضعها. ولا يدخل `detail` فيه عن قصد — التفصيل يتغيّر
     * بتفاصيل الجهاز (اسم ملفّ، مسار) فلا يصلح أن يكون هويّة الدليل.
     *
     * **ووظيفته إزالة التكرار وحده، لا العدّ:** `HOOK_FRAMEWORK_MAPPED@PROCESS` و
     * `HOOK_FRAMEWORK_MAPPED@SERVICE` مفتاحان مختلفان فلا يُطبع الدليل مرّتين في التشخيص،
     * لكنّهما **إشارة واحدة** ولا يُحكمان معًا بالتلاعب (انظر [IntegrityLedger.evaluate]).
     */
    val key: String get() = signal.name + "@" + checkpoint.name
}

/** حصيلة التحقّق. والرفض على [TAMPERED] وحده؛ و[SUSPECTED] تُسجَّل ولا تمنع. */
enum class IntegrityVerdict {
    CLEAN,

    /** إشارة غير قاطعة واحدة — لا تُبرَّر بحالة سليمة ولا بحالة معدَّلة، فتُسجَّل وتُنتظر الثانية. */
    SUSPECTED,

    TAMPERED,
}
